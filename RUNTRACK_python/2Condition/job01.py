valeur1 = int(input("Entrez une valeur pour valeur1 : "))
valeur2 = int(input("Entrez une valeur pour valeur2 : "))

if  valeur1 < valeur2:
    print("valeur1 est plus petite que valeur2")
elif valeur1 > valeur2:
    print("valeur1 est plus grande que valeur2")
else:
    print("valeur1 est égale à valeur2")